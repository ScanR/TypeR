const assert = require("assert");
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { unzipSync } = require("fflate");
const { verifiedBinary } = require("./buildKeysAddon");
const root = path.resolve(__dirname, "..");
const archive = path.join(root, process.argv.includes('--release') ? "Releases/UXP-Windows.ccx" : "Releases/TypeR-UXP-addon-win.ccx");
const bytes = fs.readFileSync(archive);
const entries = unzipSync(bytes);
const manifest = JSON.parse(Buffer.from(entries["manifest.json"]).toString("utf8"));
assert.strictEqual(manifest.id, "com.scanr.typer");
assert.strictEqual(manifest.version, require("../package.json").version);
assert.strictEqual(manifest.manifestVersion, 6);
assert.strictEqual(manifest.name, "TypeR");
assert.deepStrictEqual(manifest.addon, { name: "typer-keys.uxpaddon" });
assert.strictEqual(manifest.requiredPermissions.enableAddon, true);
assert.deepStrictEqual(Buffer.from(entries["win/x64/typer-keys.uxpaddon"]), verifiedBinary());
assert(!Object.keys(entries).some((name) => /^native\//.test(name) || /\.(exe|ps1)$/i.test(name)));
const host = Buffer.from(entries["host.js"]).toString("utf8");
assert(host.includes('require("typer-keys.uxpaddon")'), "The addon must be loaded by Adobe, not bundled by webpack");
assert(host.includes("TypeR UXP addon reader v1"));
assert(!host.includes("TypeR Shortcuts.exe") && !host.includes("typer-keys-win.json"), "The preview must not include the external keyboard reader");
const sha256 = crypto.createHash("sha256").update(bytes).digest("hex");
assert.strictEqual(fs.readFileSync(archive + ".sha256", "utf8").trim(), sha256 + "  " + path.basename(archive));
console.log("Windows addon CCX verified: manifest, native DLL, source/binary hashes, direct loading and no external keyboard helper");
